def test_ja4s_and_ja3s_from_server_hello():
    from app.parsing import ja4 as J
    from app.parsing.handshake import ServerHelloInfo
    sh = ServerHelloInfo(negotiated_version=0x0304, cipher_suite=0x1301,
                         extension_ids=[43, 51], alpn=["h2"])
    fp = J.ja4s(sh)
    assert fp.startswith("s13") and "_1301_" in fp
    assert len(fp.split("_")) == 3  # EXPERIMENTAL layout documented in ja4.py
    assert len(J.ja3s_digest(sh)) == 32


def test_fuzz_fingerprint_never_raises():
    from hypothesis import given, settings as _hs, strategies as st
    from app.parsing import ja4 as J
    from app.parsing.handshake import ClientHelloInfo, ServerHelloInfo

    @_hs(max_examples=200, derandomize=True)
    @given(st.lists(st.integers(0, 0xFFFF), max_size=40),
           st.lists(st.integers(0, 0xFFFF), max_size=40),
           st.lists(st.integers(0, 0xFFFF), max_size=12))
    def _fuzz(ciphers, exts, groups):
        ch = ClientHelloInfo(cipher_suites=ciphers, supported_groups=groups,
                             extension_ids=exts, sig_algs=groups)
        J.ja4(ch)
        J.ja3(ch)
        J.ja3_digest(ch)
        sh = ServerHelloInfo(cipher_suite=ciphers[0] if ciphers else 0,
                             extension_ids=exts)
        J.ja4s(sh)
        J.ja3s(sh)

    _fuzz()


def test_deny_list_match_and_org_isolation():
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker
    from app.core.database import Base
    import app.models.entities as E
    from app.live.flows import _deny_list_hit, _deny_cache
    _deny_cache.clear()
    engine = create_engine("sqlite://")
    Base.metadata.create_all(engine)
    S = sessionmaker(bind=engine)()
    S.add(E.Organization(id="o1", name="a"))
    S.add(E.Organization(id="o2", name="b"))
    S.add(E.FingerprintList(org_id="o1", kind="deny", fp_type="ja4",
                            value="fp-bad", source="soc", comment="x",
                            created_by="a"))
    S.commit()
    assert _deny_list_hit(S, "o1", {"ja4": "fp-bad"}) == "ja4:fp-bad"
    assert _deny_list_hit(S, "o1", {"ja4": "fp-ok"}) is None
    assert _deny_list_hit(S, "o2", {"ja4": "fp-bad"}) is None  # other org unaffected
    S.close()


def test_outdated_stack_signal_and_inventory():
    from app.parsing.rules import SessionAnalysis, run_rules
    sa = SessionAnalysis(session_id="t", protocol="SMTP",
                         five_tuple="a:1-b:25", is_starttls=False)
    from app.parsing.handshake import ClientHelloInfo
    sa.client_hello = ClientHelloInfo(offered_versions=[0x0301], legacy_version=0x0301)
    run_rules(sa)
    assert "outdated-client-stack" in {f.rule_id for f in sa.findings}
    sa2 = SessionAnalysis(session_id="t", protocol="SMTP",
                          five_tuple="a:1-b:25", is_starttls=False)
    sa2.client_hello = ClientHelloInfo(offered_versions=[0x0304, 0x0303], legacy_version=0x0303)
    run_rules(sa2)
    assert "outdated-client-stack" not in {f.rule_id for f in sa2.findings}
