def _ch(ciphers=(0x1301, 0x1302), exts=(0, 10, 16, 43, 13), groups=(29,),
        sigalgs=(0x0403,), sni="mail.example.com", alpn=("h2",), versions=(0x0304, 0x0303)):
    from app.parsing.handshake import ClientHelloInfo
    return ClientHelloInfo(
        offered_versions=list(versions), legacy_version=0x0303,
        cipher_suites=list(ciphers), sni=sni, alpn=list(alpn),
        supported_groups=list(groups), has_supported_versions=True,
        key_share_groups=list(groups), sig_algs=list(sigalgs),
        extension_ids=list(exts), ec_point_formats=[0])


def test_ja4_shape_and_grease_invariance():
    from app.parsing import ja4 as J
    ch = _ch()
    fp = J.ja4(ch)
    parts = fp.split("_")
    assert len(parts) == 3 and fp.startswith("t13d")
    assert len(parts[1]) == 12 and len(parts[2]) == 12
    # GREASE anywhere must not change the fingerprint
    ch_g = _ch(ciphers=(0x0A0A, 0x1301, 0x1302, 0x1A1A),
               exts=(0, 10, 0x2A2A, 16, 43, 13), groups=(29, 0x3A3A))
    assert J.ja4(ch_g) == fp
    assert J.ja3(ch_g) == J.ja3(ch)


def test_ja4_ordering_rules():
    from app.parsing import ja4 as J
    # JA4 sorts extensions; classic JA3 preserves offered order.
    a = _ch(exts=(0, 10, 16, 43, 13))
    b = _ch(exts=(13, 43, 16, 10, 0))
    assert J.ja4(a) == J.ja4(b)
    assert J.ja3(a) != J.ja3(b)  # JA3 is order-sensitive by design
    no_sni = _ch(sni=None)
    assert J.ja4(no_sni)[3] == "i"
    assert J.ja4(no_sni) != J.ja4(a)
    # ALPN changes the fingerprint (first/last chars captured)
    assert J.ja4(_ch(alpn=("http/1.1",))) != fp if (fp := J.ja4(a)) else False


def test_ja4_spec_hash_halves_match_published():
    # The only independently verifiable anchors: the two intermediate hashes
    # printed in the FoxIO JA4 spec document itself.
    assert hashlib.sha256(
        "002f,0035,009c,009d,1301,1302,1303,c013,c014,c02b,c02c,c02f,c030,cca8,cca9"
        .encode()).hexdigest()[:12] == "8daaf6152771"
    assert hashlib.sha256(
        ("0005,000a,000b,000d,0012,0015,0017,001b,0023,002b,002d,0033,4469,ff01"
         "_0403,0804,0401,0503,0805,0501,0806,0601").encode()).hexdigest()[:12] == "e5627efa2ab1"


